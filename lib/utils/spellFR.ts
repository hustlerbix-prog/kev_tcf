type Token = { w: string; i: number; l: number };

const FR_WORD_CHARS = /[A-Za-zÀ-ÖØ-öø-ÿ'\-]/;

const tokensOf = (text: string): Token[] => {
  const res: Token[] = [];
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (FR_WORD_CHARS.test(c)) {
      let j = i;
      while (j < n && FR_WORD_CHARS.test(text[j])) j++;
      const w = text.slice(i, j);
      if (w.length >= 2) res.push({ w, i, l: j - i });
      i = j;
    } else {
      i++;
    }
  }
  return res;
};

