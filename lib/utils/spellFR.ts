const diacriticFold = (s: string): string =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();

// Build regex alternation of EXACT entries for FAST match (compiled once per call context reuse)
let _cachedReg: RegExp | null = null;
const getReg = (): RegExp => {
  if (_cachedReg) return _cachedReg;
  const keys = Object.keys(ERRORS_EXACT_LOWER).filter((k) => k.length >= 2);
  keys.sort((a, b) => b.length - a.length);
  const escaped = keys.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  _cachedReg = new RegExp("\\b(" + escaped.join("|") + ")\\b", "gi");
  return _cachedReg;
};

export const FR_COMMON_SPELL_ERRORS = ERRORS_EXACT_LOWER;

export type SpellOptions = {
  includeRule?: boolean;
  maxMatches?: number;
  // Allow diacritic-less near-match correction? Off by default, use exact casefold dict
  diacriticNearMatch?: boolean;
};

export function analyseOrthographe(
  text: string,
  opts: SpellOptions = {}
): SpellMatch[] {
  if (!text || text.length < 2) return [];
  const out: SpellMatch[] = [];
  const reg = getReg();
  const max = opts.maxMatches ?? 400;
  let m: RegExpExecArray | null;
  reg.lastIndex = 0;
  let iter = 0;
  while ((m = reg.exec(text)) !== null && iter < max) {
    iter++;
    const wrongFull = m[1];
    const lower = wrongFull.toLowerCase();
    const entry = ERRORS_EXACT_LOWER[lower];
    if (!entry) continue;
    // Suggestion = identité → skip (faux positif: entrée identique dans dict pour raisons de cohérence)
    if (entry.s && entry.s.toLowerCase() === lower) continue;
    const start = m.index + m[0].indexOf(wrongFull);
    const end = start + wrongFull.length;
    // Preserve capitalization? We don't for now; just use suggestion raw.
    out.push({
      start,
      end,
      wrong: wrongFull,
      suggestion: entry.s,
      rule: opts.includeRule ? entry.r || undefined : undefined,
    });
  }
  if (!opts.diacriticNearMatch) return out;
  // Second pass for diacritic near-matches (e.g., "etre" already in exact dict above, so rarely used)
  const toks = tokensOf(text);
  for (let k = 0; k < toks.length && out.length < max; k++) {
    const t = toks[k];
    const fold = diacriticFold(t.w);
    if (ERRORS_EXACT_LOWER[LIGNE(t.w)]) continue;
    // Check folded matches any known correction diacritic-folded (one-to-one):
    const candidateKey = Object.keys(ERRORS_EXACT_LOWER).find(
      (key) => diacriticFold(key) === fold && diacriticFold(ERRORS_EXACT_LOWER[key].s) === fold
    );
    if (candidateKey) {
      const suggestion = ERRORS_EXACT_LOWER[candidateKey].s;
      if (suggestion.toLowerCase() !== t.w.toLowerCase()) {
        out.push({
          start: t.i,
          end: t.i + t.l,
          wrong: t.w,
          suggestion,
          rule: opts.includeRule
            ? ERRORS_EXACT_LOWER[candidateKey].r || "Accents manquants"
            : undefined,
        });
      }
    }
  }
  // Stable sort by start index
  out.sort((a, b) => a.start - b.start);
  // Filter overlaps: if next.start < prev.end (keep first)
  const dedup: SpellMatch[] = [];
  let lastEnd = -1;
  for (const m2 of out) {
    if (m2.start >= lastEnd) {
      dedup.push(m2);
      lastEnd = m2.end;
    }
  }
  return dedup;
}
