def main():
    lines = []
    lines.append("-- Migration 011 : Seed des 72 archetypes EO selon EO-001 §8")
    lines.append("-- Idempotent : DELETE régulé puis INSERT ... ON CONFLICT DO UPDATE")
    lines.append("")
    lines.append("DELETE FROM eo_archetypes WHERE id ~ '^T[123]-';")
    lines.append("")

    # T1
    for id_, ordre, cat, cons, qopen, set_, rel in T1_DATA:
        lines.append(t1(id=id_, ordre=ordre, categorie=cat, consigne=cons,
                        question_ouverture=qopen, set=set_, relances=rel))
        lines.append("")

    # T2
    for (id_, ordre, cat, cons, qopen, set_, rm, exam, cand, sf, comp, lf) in T2_DATA:
        lines.append(t2(id=id_, ordre=ordre, categorie=cat, consigne=cons,
                        question_ouverture=qopen, set=set_, required_moves=rm,
                        examiner_role=exam, candidate_role=cand, scene_facts=sf,
                        complication=comp, lexical_field=lf))
        lines.append("")

    # T3 : 9 quick-set rows have 10 items, 19 full rows have 7 items
    for row in T3_DATA:
        if len(row) == 10:
            (id_, ordre, cat, cons, qopen, tag, ap, ac, ec, lf) = row
            lines.append(t3_qs(id=id_, ordre=ordre, categorie=cat, consigne=cons,
                               question_ouverture=qopen, arguments_pour=ap,
                               arguments_contre=ac, exemples_concrets=ec,
                               lexical_field=lf))
        elif len(row) == 7:
            (id_, ordre, cat, cons, qopen, tag, lf) = row
            lines.append(t3_full(id=id_, ordre=ordre, categorie=cat, consigne=cons,
                                 question_ouverture=qopen, lexical_field=lf))
        else:
            raise ValueError(f"Bad T3_DATA row length {len(row)}: id candidate = {row[0]!r}")
        lines.append("")

    content = "\n".join(lines)
    with open(SQL_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"OK — wrote SQL to {SQL_PATH}")

    # sanity checks
    insert_count = content.count("\nINSERT INTO eo_archetypes")
    # also matches starting with INSERT
    import re
    insert_count = len(re.findall(r"^INSERT INTO eo_archetypes", content, re.MULTILINE))
    print(f"INSERT statements count (grep ^INSERT): {insert_count}")

if __name__ == "__main__":
    main()
